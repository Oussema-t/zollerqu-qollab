"""Figures and a short report for option C (many devices: A = which devices to use, B = split the mesh among them).

inputs : results/multidevice/stage_a_device_choice.json, stage_b_recursive_split.json (scripts/multidevice_c.py)
outputs: results/multidevice/figures/*.png, results/multidevice/REPORT.md
usage  : python scripts/make_multidevice_report.py
"""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
DIR = ROOT / "results" / "multidevice"
FIG = DIR / "figures"
FIG.mkdir(parents=True, exist_ok=True)
plt.rcParams.update({"font.size": 11, "axes.spines.top": False, "axes.spines.right": False, "savefig.dpi": 160})
GOALS = ["fastest", "overnight", "lowest energy"]
SHORT_METHOD = {"local search": "local\nsearch", "simulated annealing": "simulated\nannealing", "spectral bisection": "spectral",
                "random, target share": "random\n(target share)"}
METHOD_STYLE = {"LR-QAOA": ("#E69F00", "v", "--"), "QAOA, angles optimised on calibration pools": ("#0072B2", "o", "-")}


def figure_a(a):
    fig, axes = plt.subplots(1, 3, figsize=(12, 3.9), sharey=True)
    for ax, goal in zip(axes, GOALS):
        rows = a["goals"][goal]["rows"]
        for method, (colour, marker, line) in METHOD_STYLE.items():
            pts = sorted((r["p"], r["test_mean_p_opt"]) for r in rows if r["method"] == method)
            ax.plot(*zip(*pts), color=colour, marker=marker, linestyle=line, label=method.replace(", angles", ",\nangles"))
        rnd = rows[0]["test_mean_random"]
        ax.axhline(rnd, color="k", linestyle=":", label="random choice (per shot)")
        ax.set_yscale("log")
        ax.set_xlabel("QAOA depth p")
        ax.set_title(f"{goal} ({rows[0]['test_pools']} test pools)", fontsize=11)
        ax.grid(alpha=0.3, which="both")
    axes[0].set_ylabel("test pools: mean P(best device set)\nper shot")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, [l.replace("\n", " ") for l in labels], fontsize=9, loc="lower center", ncol=3, frameon=False)
    fig.suptitle("A. Which devices to use (8-10 devices = qubits; general diagonal cost, angles chosen on 10 calibration pools)", fontsize=11)
    fig.tight_layout(rect=(0, 0.08, 1, 1))
    path = FIG / "stage_a_device_choice.png"
    fig.savefig(path)
    plt.close(fig)
    return path


def figure_b(b):
    methods = list(b[GOALS[0]]["methods"])
    fig, axes = plt.subplots(1, 3, figsize=(12, 4.4), sharey=True)
    for ax, goal in zip(axes, GOALS):
        g = b[goal]
        x = np.arange(len(methods))
        compute = [g["methods"][m]["compute_hours"] for m in methods]
        comm = [g["methods"][m]["comm_hours"] for m in methods]
        ax.bar(x, compute, color="#0072B2", label="compute (slowest device)")
        ax.bar(x, comm, bottom=compute, color="#999999", hatch="//", edgecolor="white", label="communication over the cut")
        ax.axhline(g["plan_hours"], color="#D55E00", linestyle="--", label="plan (ideal shares, compute only)")
        for i, m in enumerate(methods):
            r = g["methods"][m]
            ax.text(i, compute[i] + comm[i] + 0.3, f"{r['splits_optimal']}/{r['n_splits']}" + ("\nmem!" if r["memory_overload"] > 0.05 else ""),
                    ha="center", va="bottom", fontsize=8)
        ax.set_xticks(x, [SHORT_METHOD.get(m, m) for m in methods], fontsize=8)
        ax.set_ylim(0, 28)
        ax.set_title(f"{goal}: {len(g['devices'])} devices", fontsize=11)
        ax.grid(alpha=0.3, axis="y")
    axes[0].set_ylabel("modelled hours for the 300 h reference job")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, fontsize=9, loc="lower center", ncol=3, frameon=False)
    fig.suptitle("B. Mesh '2 main' (24 regions) split recursively among the chosen devices "
                 "(label: splits solved exactly; 'mem!' = memory limit exceeded by > 5 %)", fontsize=10)
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    path = FIG / "stage_b_split.png"
    fig.savefig(path)
    plt.close(fig)
    return path


def split_text(split):
    outcome = "optimal" if split["optimal"] else f"gap {split['gap_percent']:.1f} %"
    return f"{split['regions']} regions: P(opt) {split['p_opt']:.3f}, best of 1,000 shots {outcome}"


if __name__ == "__main__":
    a = json.loads((DIR / "stage_a_device_choice.json").read_text())
    b = json.loads((DIR / "stage_b_recursive_split.json").read_text())
    figs = [figure_a(a), figure_b(b)]
    lines = ["# Option C: many devices (generated by `scripts/make_multidevice_report.py` from saved results)", "",
             "Device pools are synthetic (Task 03b model: speed, memory cap, busy / idle power per device); hours and kWh are modelled "
             "for the 300 h reference job, not measured. Noiseless simulation. Every answer is graded against the exact optimum "
             "(enumeration). No claim of quantum advantage.", "",
             "## A. Which devices to use (one qubit per device)", "",
             "| goal | test pools | depth p | setting (chosen on 10 calibration pools) | test mean P(best set) per shot | random | most likely = best set | calibration evals |",
             "|---|---|---|---|---|---|---|---|"]
    for goal in GOALS:
        for r in sorted(a["goals"][goal]["rows"], key=lambda r: (r["p"], r["method"])):
            lines.append(f"| {goal} | {r['test_pools']} | {r['p']} | {r['method']} | {r['test_mean_p_opt']:.3f} | {r['test_mean_random']:.4f} | "
                         f"{r['test_most_likely_optimal']}/{r['test_pools']} | {r['calibration_evaluations']} |")
    p7 = a["goals"]["fastest"]["pool7"]
    lines += ["", f"Cost circuit: the goal is not quadratic in the device bits, so the cost layer is a general diagonal with terms up to "
              f"{max(map(int, p7['diagonal_terms_by_weight']))}-body ({p7['cnot_per_cost_layer_general_diagonal']} CNOT per layer at 8 devices). "
              "A 2-local (Ising) approximation loses the optimum: rank of the true best set under it = " + ", ".join(
                  f"{g}: {a['goals'][g]['pool7']['quadratic_approximation_rank_of_true_optimum']}" for g in GOALS) + " (pool seed 7).", "",
              "## B. Split the mesh among the chosen devices (pool seed 7, mesh '2 main', 24 regions)", "",
              "Recursive bisection: the devices are split into two groups with shares as equal as possible; the regions are split with the "
              "notebook's Ising model (target share = the group's share); repeat inside each group. QAOA: LR schedule calibrated on the "
              "12-region calibration meshes (never scored), best of 1,000 shots per split. lambda per split: smallest grid value whose "
              "exact optimum is balanced (uses enumeration; all methods solve the same Hamiltonian).", "",
              "| goal | devices | method | splits solved exactly | max share error | memory overload | cut fraction | compute h | comm h | modelled h | kWh |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    for goal in GOALS:
        g = b[goal]
        lines.append(f"| {goal} | {len(g['devices'])} | plan (ideal shares, no cut) | | | | | {g['plan_hours']:.2f} | | | {g['plan_kwh']:.2f} |")
        for m, r in g["methods"].items():
            lines.append(f"| {goal} | {len(g['devices'])} | {m} | {r['splits_optimal']}/{r['n_splits']} | {r['max_share_error']:.3f} | "
                         f"{r['memory_overload']:.3f} | {r['cut_fraction']:.3f} | {r['compute_hours']:.2f} | {r['comm_hours']:.2f} | "
                         f"{r['modelled_hours']:.2f} | {r['modelled_kwh']:.2f} |")
    qaoa_splits = [s for goal in GOALS for s in b[goal]["methods"]["QAOA"]["splits"]]
    lines += ["", "QAOA per split (all goals): " + "; ".join(split_text(s) for s in qaoa_splits), "",
              "## What this does not show", "",
              "- One test pool and one mesh for part B; part A has 5 test pools (2 for the overnight goal, where only 2 pools have a feasible set).",
              "- The exact optimum of each split is not the best plan for modelled hours: the Ising cost (cut + balance) and the hours model "
              "weigh the cut differently (e.g. spectral bisection: fewer hours on the overnight goal but 18 % over the memory limits).",
              "- No noise and no hardware run for option C; the device-choice circuit (general diagonal) is far deeper than the mesh-split circuit.",
              "", "## Figures", ""] + [f"- `{f.relative_to(ROOT)}`" for f in figs]
    (DIR / "REPORT.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {DIR / 'REPORT.md'} and {len(figs)} figures")

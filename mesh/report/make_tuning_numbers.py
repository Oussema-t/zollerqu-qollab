"""LaTeX macros for the paper's IonQ-run and QAOA-tuning sections, read from the result files (nothing typed by hand):
report/numbers_tuning.tex.   usage: python report/make_tuning_numbers.py
"""
import glob
import json
import re
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
out = {}


def hit(values):
    """Percent, rounded; 99.5-99.99 keeps one decimal so it is never shown as 100."""
    v = 100 * float(np.mean(values))
    return f"{v:.1f}" if 99.5 <= v < 100 else f"{v:.0f}"
run = json.loads((ROOT / "qollab/results_ionq/2026-10-11_varqite_zy_equal_ionq_simulator.json").read_text())
sel = json.loads((ROOT / "qollab/selected_circuits.json").read_text())
zy = next(c for c in sel["circuits"] if c["name"].startswith("varQITE ZY"))
s = run["summary"][0]
out["IonQPopt"] = f"{100 * s['p_opt']:.1f}"
out["IonQShots"] = f"{s['shots']:,}".replace(",", "\\,")
out["IonQNoiseless"] = f"{100 * zy['predicted']['p_opt']:.0f}"
out["IonQRandom"] = f"{100 * sel['instances']['2 equal devices']['uniform_p_opt']:.3f}"
second = (ROOT / "qollab/results_ionq/2026-10-11_varqite_zy_equal_run2_summary.txt").read_text()
out["IonQPoptSecond"] = f"{100 * float(re.search(r'P\(optimum\) measured ([0-9.]+)', second).group(1)):.1f}"
out["IonQTwoQubit"] = str(zy["gates"]["two_qubit"])

tuning = json.loads((ROOT / "results/qaoa_tuning/tuning_n12_large_calibration.json").read_text())
SC = {"2 equal devices": "Eq", "CPU + GPU (GPU 4x)": "Cpu"}
for scenario, tag in SC.items():
    block = tuning["scenarios"][scenario]
    best = max((r for r in block["rows"] if r["p"] == 8 and "warm" not in r["method"]), key=lambda r: r["calibration_p_near"])
    out[f"TuneTwelve{tag}"] = f"{100 * best['test']['p_near']:.1f}"
    out[f"TuneBefore{tag}"] = f"{100 * block['references']['per-shot QAOA + COBYLA p=2 (existing)']:.2f}"
for scenario, tag in SC.items():
    slug = "".join(c if c.isalnum() else "_" for c in scenario).strip("_")
    r20 = json.loads((ROOT / f"results/qaoa_tuning/scaling/n20_{slug}_p6.json").read_text())["methods"]["re-optimised at n = 20"]["test_mean"]
    out[f"TuneTwenty{tag}"] = f"{100 * r20['p_near']:.2f}"
    earlier = json.loads((ROOT / "scripts/q29_choice.json").read_text())["choice"][scenario]["best_fixed"]["p_near_n20"]
    out[f"TuneTwentyBefore{tag}"] = f"{100 * earlier:.3f}"
    for n in (24, 29):
        recs = [json.loads(Path(f).read_text()) for f in glob.glob(str(ROOT / f"results/qaoa_tuning/hpc/hpc_n{n}/*_seed*_*.json"))]
        recs = [r for r in recs if r["scenario"] == scenario]
        word = {24: "TwentyFour", 29: "TwentyNine"}[n]
        out[f"Tune{word}Qaoa{tag}"] = hit([next(q['hit_near'] for q in r['quantum'] if q['p'] == 8) for r in recs])
        out[f"Tune{word}Gates"] = str(recs[0]["quantum"][-1]["two_qubit_gates"])
        for m, key in (("spectral bisection", "Spec"), ("simulated annealing", "Anneal"), ("local search (restarts)", "Local")):
            out[f"Tune{word}{key}{tag}"] = hit([r['classical'][m]['hit_near'] for r in recs])
    first29 = [json.loads(Path(f).read_text()) for f in glob.glob(str(ROOT / "results/hpc_n29/*_seed*_*.json"))]
    out[f"TuneFirstTwentyNine{tag}"] = f"{100 * np.mean([q['hit_near'] for r in first29 if r['scenario'] == scenario for q in r['quantum'] if 'best fixed' in q['label']]):.1f}"
lines = ["% generated by report/make_tuning_numbers.py from the result files"] + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in out.items()]
(ROOT / "report/numbers_tuning.tex").write_text("\n".join(lines) + "\n")
print("\n".join(lines))

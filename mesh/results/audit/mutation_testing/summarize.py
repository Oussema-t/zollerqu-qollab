"""Summarise the mutation-testing logs (30 deliberately injected bugs in the Task 04 code) into SUMMARY.md and summary.json.
Round 1 logs are empty (the first batch was interrupted); round 2 ran all mutants; round 3 re-ran the survivors after the unit
tests were added; round 4 re-ran the last two. A mutant counts as caught when the run crashed on a check (assertion) or finished
with an instance-level failure recorded by a check; it survives when the run finished with no failure.
usage: python results/audit/mutation_testing/summarize.py
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
rounds = {}
for number in (2, 3, 4):
    for log in sorted((HERE / "logs" / f"round_{number}").glob("mut_*.log")):
        text = log.read_text(errors="replace")
        status = re.search(r"\[STATUS\] (\w+)(.*)", text)
        failures = re.findall(r"failures: (\[.+\])", text)
        recorded = [f for f in failures if f != "[]"]
        if status is None:
            outcome, detail = "no status line", ""
        elif status.group(1) == "CRASH":
            outcome, detail = "caught (run stopped by a check)" if "AssertionError" in status.group(2) else "crashed (not a designed check)", status.group(2).strip()
        elif recorded:
            errors = sorted(set(re.findall(r"'error': '([^']+)'", " ".join(recorded))))
            outcome, detail = "caught (instance failure recorded by a check)", "; ".join(errors)
        else:
            outcome, detail = "survived", ""
        detail = re.sub(r"\s*\[[\d.]+ s\]$", "", detail)
        if outcome.startswith("caught") and detail.rstrip(":") in ("AssertionError", ""):   # no message: name the failing check
            check = re.findall(r"cell line \d+ in [^:]+: (assert .+)", text)
            detail = f"AssertionError at `{check[-1][:150]}`" if check else detail
        rounds.setdefault(log.stem, {})[number] = dict(outcome=outcome, detail=detail)
final = {name: per_round[max(per_round)] | dict(round=max(per_round)) for name, per_round in rounds.items()}
caught = sum(v["outcome"].startswith("caught") for v in final.values())
lines = ["# Mutation testing: 30 injected bugs in the Task 04 code", "",
         f"Final result: **{caught} of {len(final)} mutants caught** (latest round per mutant). Generated by `summarize.py` from `logs/`.", "",
         "Each mutant changes one line of the Task 04 code that was under review (see `../code_under_review/`; the string patches "
         "in `harness/make_mut.py` target that version, which is earlier than the committed notebook cell). Round 2 ran all mutants. "
         "Unit tests were then added to the notebook (LR schedule, metrics, outcome model, SPSA, masks, scaled energies, relaxation, "
         "annealing / local-search descent, spectral threshold, piece count, noise formula, hit formula), and rounds 3 and 4 re-ran the survivors. "
         "Round 1 logs are empty because that batch was interrupted.", "",
         "| mutant | round 2 | round 3 | round 4 | final | caught by |", "|---|---|---|---|---|---|"]
for name in sorted(final):
    cells = [rounds[name].get(k, {}).get("outcome", "").replace("caught (run stopped by a check)", "caught").replace(
        "caught (instance failure recorded by a check)", "caught (recorded)") for k in (2, 3, 4)]
    lines.append(f"| `{name}` | " + " | ".join(cells) + f" | {final[name]['outcome']} | {final[name]['detail'] or '-'} |")
(HERE / "SUMMARY.md").write_text("\n".join(lines) + "\n")
(HERE / "summary.json").write_text(json.dumps(dict(caught=caught, total=len(final), final=final, rounds=rounds), indent=1))
print(f"{caught} of {len(final)} mutants caught; SUMMARY.md and summary.json written")

def build_circuit(spec):
    """H on all qubits; per layer rzz(2 g J/scale), rz(2 gF h/scale), rx(2 b) [, ry(2 a)]; measure_all."""
    model, angles = spec["model"], spec["angles"]
    n, scale = len(TICKERS), model["scale"]
    gammas, betas = angles["gammas"], angles["betas"]
    field_gammas = angles.get("field_gammas") or gammas
    alphas = angles.get("alphas")
    qc = QuantumCircuit(n, name=spec["name"])
    qc.h(range(n))
    for k in range(len(gammas)):
        for i, j, coupling in model["pair_terms"]:
            qc.rzz(2.0 * gammas[k] * coupling / scale, i, j)
        for i, h in enumerate(model["fields"]):
            if h != 0.0:
                qc.rz(2.0 * field_gammas[k] * h / scale, i)
        for q in range(n):
            qc.rx(2.0 * betas[k], q)
        if alphas is not None:
            for q in range(n):
                qc.ry(2.0 * alphas[k], q)
    qc.measure_all()
    return qc


def energy(bits, model):
    """Ising energy of a count key (qubit 0 is the rightmost character; '0' = spin +1)."""
    spins = [1.0 if bit == "0" else -1.0 for bit in bits[::-1]]
    value = model["const"] + sum(h * s for h, s in zip(model["fields"], spins))
    value += sum(coupling * spins[i] * spins[j] for i, j, coupling in model["pair_terms"])
    return value


def describe(bits, mode):
    spins = [1 if bit == "0" else -1 for bit in bits[::-1]]
    plus = [t for t, s in zip(TICKERS, spins) if s > 0]
    minus = [t for t, s in zip(TICKERS, spins) if s < 0]
    return ("long: " + ", ".join(plus) + " | short: " + ", ".join(minus)) if mode == "long_short" \
        else ("buy: " + (", ".join(plus) or "nothing") + " | skip: " + ", ".join(minus))


def analyse(counts, model, mode):
    """P(optimum), share within 5 % of the optimum, quality of the sampled energies, most frequent portfolio."""
    exact = EXACT[mode]
    e_min, e_max = exact["e_min"], exact["e_max"]
    tolerance = 1e-9 * (e_max - e_min)
    total = hits = near = 0
    weighted = 0.0
    for key, count in counts.items():
        bits = key.replace(" ", "")
        e = energy(bits, model)
        total += count
        weighted += count * e
        hits += count * (e <= e_min + tolerance)
        near += count * (e <= e_min + WITHIN * (e_max - e_min))
    mean = weighted / total
    top = max(counts, key=counts.get).replace(" ", "")
    return {"shots": total, "p_optimum": hits / total, "p_within_5pct": near / total,
            "quality": (e_max - mean) / (e_max - e_min), "mean_energy": mean,
            "most_frequent": top, "most_frequent_count": counts[max(counts, key=counts.get)],
            "most_frequent_is_optimum": top == exact["bitstring"], "most_frequent_energy": energy(top, model)}


def local_counts(circuits, shots, seed):
    """Noiseless shots sampled from the exact state (used only when no backend is available)."""
    rng = np.random.default_rng(seed)
    out = []
    for qc in circuits:
        probabilities = np.asarray(Statevector.from_instruction(qc.remove_final_measurements(inplace=False)).probabilities())
        draws = rng.choice(len(probabilities), size=shots, p=probabilities / probabilities.sum())
        counts = {}
        for index in draws:
            key = format(int(index), "0" + str(qc.num_qubits) + "b")
            counts[key] = counts.get(key, 0) + 1
        out.append(counts)
    return out


def energy_table(counts, model):
    """(energy, count) per measured portfolio."""
    return [(energy(key.replace(" ", ""), model), count, key.replace(" ", "")) for key, count in counts.items()]


def ideal_distribution(qc, model):
    """Exact noiseless probabilities of the circuit, as (energy, probability) per basis state (12 qubits: instant)."""
    probabilities = np.asarray(Statevector.from_instruction(qc.remove_final_measurements(inplace=False)).probabilities())
    n = qc.num_qubits
    energies = np.array([energy(format(index, "0%db" % n), model) for index in range(len(probabilities))])
    return energies, probabilities


def text_charts(counts, qc, model, mode, shots, source):
    """Console version of the figures (shown in every environment)."""
    exact = EXACT[mode]
    e_min, e_max = exact["e_min"], exact["e_max"]
    edges = np.linspace(e_min, e_max, 16)
    measured = np.zeros(15)
    for e, count, _ in energy_table(counts, model):
        k = min(int((e - e_min) / (e_max - e_min) * 15), 14)
        measured[max(k, 0)] += count
    energies, probabilities = ideal_distribution(qc, model)
    ideal = np.array([probabilities[(energies >= lo) & (energies < hi if hi < e_max else energies <= hi)].sum() * shots for lo, hi in zip(edges[:-1], edges[1:])])
    print("Portfolio score of the measured shots (left = better; first row contains the exact optimum):")
    print("  %-22s %-27s %7s %7s" % ("score range", "measured shots", "shots", "ideal"))
    for lo, hi, m, i in zip(edges[:-1], edges[1:], measured, ideal):
        print("  %+.4f..%+.4f  %-27s %7d %7.0f" % (lo, hi, "#" * int(round(25 * m / max(measured.max(), 1))), m, i))
    print("  ideal = shots x exact noiseless probability of the same circuit; measured = %s" % source)
    top = sorted(energy_table(counts, model), key=lambda t: -t[1])[:10]
    print("Ten most frequent portfolios:")
    for e, count, bits in top:
        tag = "OPTIMUM" if bits == exact["bitstring"] else ("within 5%" if e <= e_min + WITHIN * (e_max - e_min) else "")
        print("  %s  x%-4d score %+.4f  %-9s %s" % (bits, count, e, tag, describe(bits, mode)))


def plots(counts, qc, model, mode, shots, source, title):
    """Two figures: measured score histogram vs the ideal distribution, and the ten most frequent portfolios."""
    try:
        import matplotlib.pyplot as plt
    except Exception as err:
        print("(matplotlib not available here: %s; the text charts above are the presentation)" % err)
        return
    exact = EXACT[mode]
    e_min, e_max = exact["e_min"], exact["e_max"]
    edges = np.linspace(e_min, e_max, 31)
    table = energy_table(counts, model)
    energies, probabilities = ideal_distribution(qc, model)
    fig, axes = plt.subplots(1, 2, figsize=(13, 4.5))
    ax = axes[0]
    ax.hist([e for e, _, _ in table], bins=edges, weights=[c for _, c, _ in table], color="#2a78d6", alpha=0.85, label="measured shots (%s)" % source)
    ax.hist(energies, bins=edges, weights=probabilities * shots, histtype="step", color="#eb6834", linewidth=2, label="ideal: exact noiseless x shots")
    ax.axvline(e_min, color="black", linestyle="--", linewidth=1.5, label="exact optimum")
    ax.axvline(e_min + WITHIN * (e_max - e_min), color="#888888", linestyle=":", linewidth=1.5, label="within 5 % of the optimum")
    ax.set_xlabel("portfolio score (lower is better)")
    ax.set_ylabel("number of shots")
    ax.set_title("%s: measured vs ideal" % title, loc="left", fontsize=10)
    ax.legend(frameon=False, fontsize=8)
    ax.spines[["top", "right"]].set_visible(False)
    ax = axes[1]
    top = sorted(table, key=lambda t: -t[1])[:10]
    colors = ["#1baf7a" if bits == exact["bitstring"] else ("#2a78d6" if e <= e_min + WITHIN * (e_max - e_min) else "#b4b2a9") for e, _, bits in top]
    y = np.arange(len(top))
    ax.barh(y, [c for _, c, _ in top], color=colors)
    ax.set_yticks(y, ["%s  (%+.4f)" % (bits, e) for e, _, bits in top], fontsize=8)
    ax.invert_yaxis()
    ax.set_xlabel("shots")
    ax.set_title("ten most frequent portfolios (green = exact optimum, blue = within 5 %)", loc="left", fontsize=10)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    plt.show()


def run_backend(circuit, backend, shots, wait_minutes):
    """ONE circuit per job (IonQ accepts only ionq.circuit.v1); prints the status every 10 s; returns counts or None."""
    compiled = transpile(circuit, backend, optimization_level=1)
    try:
        job = backend.run(compiled, shots=shots)
    except Exception as err:  # qiskit-ionq can hide the real error behind an AttributeError
        print("Backend run failed:", type(err).__name__, err)
        return None
    print("Job submitted:", getattr(job, "job_id", lambda: "?")())
    started = time.time()
    while time.time() - started < 60 * wait_minutes:
        try:
            status = job.status()
        except Exception as err:
            print("status check failed:", type(err).__name__, err)
            break
        name = getattr(status, "name", str(status))
        print("  status after %4.0f s: %s" % (time.time() - started, name))
        if name in ("DONE", "ERROR", "CANCELLED"):
            break
        time.sleep(10)
    try:
        return job.result().get_counts()
    except Exception as err:
        print("Could not read the result:", type(err).__name__, err)
        return None


def main(circuit: str = "B_cvar_p3", shots: int = 1000, wait_minutes: int = 60, seed: int = 2026):
    """circuit: control_p0, B_cvar_p3, A_cd_p3, B_lr_p1 or B_lr_p3 (ONE circuit per job on IonQ); shots per run."""
    print("ZollerQu stock split, 12 qubits. This effort is supported by Qollab & IonQ.")
    print("assets (qubit 0 first):", ", ".join(TICKERS))
    key = circuit.strip()
    if key not in CIRCUIT_KEYS:
        print("Unknown circuit %r. Allowed: %s. Using the default %s." % (circuit, ", ".join(CIRCUIT_KEYS), DEFAULT_CIRCUIT))
        key = DEFAULT_CIRCUIT
    chosen = CIRCUIT_KEYS[key]
    print("Circuits selected offline (noiseless numbers from the exact simulation); '>' marks the one sent now:")
    for k, name in CIRCUIT_KEYS.items():
        s = next(x for x in CIRCUITS if x["name"] == name)
        qc = build_circuit(s)
        two_qubit = sum(1 for inst in qc.data if inst.operation.num_qubits == 2)
        print("  %s %-10s %-28s mode %-11s layers %d  two-qubit gates %3d  noiseless P(optimum) %.4f" % (
            ">" if name == chosen else " ", k, name, s["mode"], len(s["angles"]["gammas"]), two_qubit, s["p_optimum_noiseless"]))
    spec = next(x for x in CIRCUITS if x["name"] == chosen)
    qc = build_circuit(spec)
    backend = globals().get("backend")  # Qollab pre-creates `backend` from the Run dialog
    counts, source = None, None
    if backend is not None:
        print("Running on:", getattr(backend, "name", backend), "| one job: %s x %d shots" % (chosen, shots))
        counts = run_backend(qc, backend, shots, wait_minutes)
        source = "backend"
    if counts is None:
        print("No backend result: sampling the exact NOISELESS probabilities locally instead (not a hardware result).")
        counts = local_counts([qc], shots, seed)[0]
        source = "local noiseless sampling"
    print()
    print("Results (%s), %d shots; P(optimum) = share of shots that are the exact best portfolio" % (source, shots))
    print("%-28s %-11s %9s %9s %8s  most frequent portfolio" % ("circuit", "scored as", "P(opt)", "<5%", "quality"))
    report = []
    modes = ["long_short", "buy_or_skip"] if spec["mode"] == "both" else [spec["mode"]]
    for mode in modes:
        model = spec["model"] if spec["mode"] != "both" else next(x["model"] for x in CIRCUITS if x["mode"] == mode)
        a = analyse(counts, model, mode)
        flag = " (= exact optimum)" if a["most_frequent_is_optimum"] else ""
        print("%-28s %-11s %9.4f %9.3f %8.3f  %s x%d%s" % (chosen, mode, a["p_optimum"], a["p_within_5pct"], a["quality"],
                                                          a["most_frequent"], a["most_frequent_count"], flag))
        print("%-28s %-11s %9s %9s %8s  %s" % ("", "", "", "", "", describe(a["most_frequent"], mode)))
        report.append({"circuit": chosen, "scored_as": mode, **a})
    print()
    print("Exact optima for reference:", {m: EXACT[m]["bitstring"] for m in EXACT})
    print()
    for mode in modes:
        model = spec["model"] if spec["mode"] != "both" else next(x["model"] for x in CIRCUITS if x["mode"] == mode)
        text_charts(counts, qc, model, mode, shots, source)
        plots(counts, qc, model, mode, shots, source, "%s, scored as %s" % (chosen, mode))
    payload = {"source": source, "shots": shots, "backend": None if backend is None else str(getattr(backend, "name", backend)),
               "circuit": chosen, "key": key, "counts": counts, "summary": report, "time": time.strftime("%Y-%m-%d %H:%M:%S")}
    path = "results/ionq_%s_%s.json" % (key, time.strftime("%Y%m%d-%H%M%S"))
    try:
        os.makedirs("results", exist_ok=True)
        with open(path, "w") as fh:
            json.dump(payload, fh)
        print("Saved", path, "(if this file does not appear in the project, use the RAW COUNTS line below)")
    except Exception as err:
        print("Could not save a file here (%s); copy the RAW COUNTS line below instead." % err)
    print("RAW COUNTS (copy this line to save the run):")
    print(json.dumps(payload))


if sys.platform != "emscripten":  # Qollab (Pyodide) calls main() itself; locally we call it here
    main()

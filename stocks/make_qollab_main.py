def analyse(counts, model, mode):
    """P(optimum), share within 5 % of the optimum, quality of the sampled energies, most frequent portfolio."""
    exact = EXACT[mode]
    e_min, e_max = exact["e_min"], exact["e_max"]
    tolerance = 1e-9 * (e_max - e_min)
    total = hits = near = 0
    weighted = 0.0
    for key, count in counts.items():
        bits = key.replace(" ", "")
        e = energy(bits, model)
        total += count
        weighted += count * e
        hits += count * (e <= e_min + tolerance)
        near += count * (e <= e_min + WITHIN * (e_max - e_min))
    mean = weighted / total
    top = max(counts, key=counts.get).replace(" ", "")
    return {"shots": total, "p_optimum": hits / total, "p_within_5pct": near / total,
            "quality": (e_max - mean) / (e_max - e_min), "mean_energy": mean,
            "most_frequent": top, "most_frequent_count": counts[max(counts, key=counts.get)],
            "most_frequent_is_optimum": top == exact["bitstring"], "most_frequent_energy": energy(top, model)}


def local_counts(circuits, shots, seed):
    """Noiseless shots sampled from the exact state (used only when no backend is available)."""
    rng = np.random.default_rng(seed)
    out = []
    for qc in circuits:
        probabilities = np.asarray(Statevector.from_instruction(qc.remove_final_measurements(inplace=False)).probabilities())
        draws = rng.choice(len(probabilities), size=shots, p=probabilities / probabilities.sum())
        counts = {}
        for index in draws:
            key = format(int(index), "0" + str(qc.num_qubits) + "b")
            counts[key] = counts.get(key, 0) + 1
        out.append(counts)
    return out


def energy_table(counts, model):
    """(energy, count) per measured portfolio."""
    return [(energy(key.replace(" ", ""), model), count, key.replace(" ", "")) for key, count in counts.items()]


def ideal_distribution(qc, model):
    """Exact noiseless probabilities of the circuit, as (energy, probability) per basis state (12 qubits: instant)."""
    probabilities = np.asarray(Statevector.from_instruction(qc.remove_final_measurements(inplace=False)).probabilities())
    n = qc.num_qubits
    energies = np.array([energy(format(index, "0%db" % n), model) for index in range(len(probabilities))])
    return energies, probabilities



def energy(bits, model):
    """Ising energy of a count key (qubit 0 is the rightmost character; '0' = spin +1)."""
    spins = [1.0 if bit == "0" else -1.0 for bit in bits[::-1]]
    value = model["const"] + sum(h * s for h, s in zip(model["fields"], spins))
    value += sum(coupling * spins[i] * spins[j] for i, j, coupling in model["pair_terms"])
    return value



def submit_and_wait(compiled, backend, shots, wait_minutes, options):
    """Submit one job (with extra run options), print its status every 10 s, return the counts or None."""
    try:
        job = backend.run(compiled, shots=shots, **options)
    except Exception as err:  # qiskit-ionq can hide the real error behind an AttributeError
        print("Backend run failed:", type(err).__name__, err)
        return None
    print("Job submitted:", getattr(job, "job_id", lambda: "?")(), "| options:", options or "none")
    started = time.time()
    while time.time() - started < 60 * wait_minutes:
        try:
            status = job.status()
        except Exception as err:
            print("status check failed:", type(err).__name__, err)
            break
        name = getattr(status, "name", str(status))
        print("  status after %4.0f s: %s" % (time.time() - started, name))
        if name in ("DONE", "ERROR", "CANCELLED"):
            break
        time.sleep(10)
    try:
        return job.result().get_counts()
    except Exception as err:
        print("Could not read the result:", type(err).__name__, err)
        return None


def run_backend(circuit, backend, shots, wait_minutes, noise_model=None):
    """ONE circuit per job (IonQ accepts only ionq.circuit.v1); returns counts or None.

    noise_model (e.g. 'forte-1') is passed to the IonQ simulator as its own run option; if the job is refused or
    fails with it, the same job is sent once more without it and this is printed."""
    compiled = transpile(circuit, backend, optimization_level=1)
    if noise_model and noise_model.lower() not in ("", "default", "none"):
        counts = submit_and_wait(compiled, backend, shots, wait_minutes, {"noise_model": noise_model})
        if counts is not None:
            print("Ran with the IonQ simulator noise model:", noise_model)
            return counts
        print("The job with noise_model=%r did not return counts; sending it again without that option." % noise_model)
    return submit_and_wait(compiled, backend, shots, wait_minutes, {})


def backend_noise(backend):
    """The noise model the backend reports (qiskit-ionq: options.noise_model, e.g. 'forte-1' or 'ideal'); None if unknown."""
    try:
        value = getattr(getattr(backend, "options", None), "noise_model", None)
        return None if value is None else str(value)
    except Exception:
        return None


def run_one(spec, key, detection, checks, shots, wait_minutes, seed, backend, show_figures, noise_model="forte-1"):
    """One job: build the circuit (plain or Iceberg), run it, decode, score, save; returns the saved record."""
    plain = build_circuit(spec)
    ice, info, why = build_iceberg(spec, checks) if detection == "iceberg" else (None, None, None)
    if detection == "iceberg" and ice is None:
        print("Iceberg is not available for this circuit:", why)
        print("Nothing was sent. Choose another circuit or error_detection = none.")
        return None
    qc = ice if detection == "iceberg" else plain
    res_plain = resources(plain)
    print("Circuit: %s | mode %s | layers %d | noiseless P(best per shot) %.4f" % (spec["name"], spec["mode"], len(spec["angles"]["gammas"]), spec["p_optimum_noiseless"]))
    print("  plain:   %2d qubits, %4d two-qubit gates, depth %4d" % (res_plain["qubits"], res_plain["two_qubit_gates"], res_plain["depth"]))
    res = res_plain
    if detection == "iceberg":
        res = resources(ice)
        print("  Iceberg: %2d qubits, %4d two-qubit gates, depth %4d (14 code qubits + 1 flag + 2 ancillas x %d checks after layers %s)" % (
            res["qubits"], res["two_qubit_gates"], res["depth"], info["checks"], info["checks_after_layers"]))
    counts, source, compiled_two = None, None, None
    if backend is not None:
        print("Running on:", getattr(backend, "name", backend), "| noise model reported by the backend:", backend_noise(backend) or "not reported",
              "| one job: %s, %s, %d shots" % (spec["name"], detection, shots))
        try:
            compiled_two = sum(1 for inst in transpile(qc, backend, optimization_level=1).data if inst.operation.num_qubits == 2)
        except Exception:
            compiled_two = None
        reported = backend_noise(backend)
        request = noise_model
        if reported and reported.lower() not in ("ideal", "none", ""):
            print("Using the noise model chosen in Select QPU:", reported)
            request = None   # the dialog already set a noise model: do not override it
        counts = run_backend(qc, backend, shots, wait_minutes, request)
        source = "backend"
    if counts is None:
        print("No backend result: sampling the exact NOISELESS probabilities locally instead (not a hardware result).")
        counts = local_counts([qc], shots, seed)[0]
        source = "local noiseless sampling"
    tally = None
    logical = counts
    if detection == "iceberg":
        logical, tally = iceberg_decode(counts, info)
        print()
        print("Iceberg error detection: %d of %d shots kept (%.1f %%); failed: flag %d, syndrome checks %d, final parity %d" % (
            tally["accepted"], tally["shots"], 100.0 * tally["accepted"] / max(tally["shots"], 1), tally["failed_flag"], tally["failed_checks"], tally["failed_parity"]))

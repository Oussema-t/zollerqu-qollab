def main():
    selected = json.loads(SELECTED_PATH.read_text())
    results = t4.load()
    exact = {}
    for mode in ising.MODES:
        e = results["models"][t4.key_of(mode, False)]["baselines"]["exact"]
        exact[mode] = {"e_min": e["e_min"], "e_max": e["e_max"], "bitstring": e["bitstring"], "assignment": e["assignment"]}
    circuits = []
    for b in selected["batch"]:
        circuits.append({"name": b["name"], "mode": b["mode"], "family": b["family"], "angles": b["angles"], "model": b["model"],
                         "p_optimum_noiseless": b["p_optimum_noiseless"]})
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    fmt = lambda obj: pprint.pformat(obj, width=118, compact=True)
    text = TEMPLATE
    for token, value in (("@@COMMIT@@", commit), ("@@TICKERS@@", fmt(selected["qubit_order"]["tickers"])), ("@@ETA@@", repr(selected["eta"])),
                         ("@@EXACT@@", fmt(exact)), ("@@CIRCUITS@@", fmt(circuits)), ("@@FALLBACK@@", repr(selected["fallback"]["name"]))):
        text = text.replace(token, value)
    MAIN_PATH.write_text(text)
    print("wrote", MAIN_PATH.relative_to(ROOT), f"({MAIN_PATH.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
